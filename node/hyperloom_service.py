"""Optional non-lab mode: systemd --user units around the same supervise (Python 3.10+, stdlib only).

Off by default, and fail closed: a root is non-lab only when its etc/install-policy.json exists and records
lab_dir explicitly null, no request carries a lab directory, and no gpu-turn files are found on the machine.
Lab machines start GPU processes only through gpu-turn leases, and leases and units never share a root. A
unit has no turn and no deadline; stop drains through supervise (SIGTERM to the main process only,
KillMode=mixed), and systemd kills what is left.
"""

import json
import os
from pathlib import Path
import posixpath
import re
import shutil
import subprocess
import sys
import time
import uuid

sys.path.insert(0, str(Path(__file__).resolve().parent))
import hyperloom_lease as lease  # noqa: E402


VERBS = {"service-install", "service-start", "service-stop", "service-status", "service-remove"}
# "No deadline": supervise still needs a finite cutoff, so a unit restarts at most once a decade.
DEADLINE_S = 10 * 365 * 86400
COPIED = ("hyperloom-node", "hyperloom_lease.py", "hyperloom_service.py")
SAFE_PATH = re.compile(r"/[A-Za-z0-9_./-]*")
LAB_FILES = ("gpu-turn.sh", "gpu-turn-pair.sh", ".gpu-turn")
# service-run exit codes. 0: requested stop. 1: engine failure (restarted). 3: readiness timeout and 4: refused
# (lab files, a lease on the root, a bad spec); systemd does not restart those (RestartPreventExitStatus).
EXIT_READY_TIMEOUT, EXIT_REFUSED = 3, 4
# Terminal service records kept per profile; older ones (and their spec/owner/log files) are pruned.
KEEP_RECORDS = 5
ACTIVE = {"active", "activating", "deactivating", "reloading"}
# StartLimitIntervalSec is well above 3 x (ready_timeout_s 600 + RestartSec 10), so three failed starts in a
# row always trip the limit instead of retrying the GPU forever.
UNIT = """# Generated by hyperloom-node (non-lab mode). Do not edit; reinstall instead.
[Unit]
Description=hyperloom non-lab service {profile}
StartLimitIntervalSec=7200
StartLimitBurst=3

[Service]
Type=simple
WorkingDirectory={root}
ExecStart={python} {root}/bin/hyperloom_service.py service-run {spec}
KillMode=mixed
KillSignal=SIGTERM
TimeoutStopSec=90
Restart=on-failure
RestartSec=10
RestartPreventExitStatus=3 4
UMask=0077

[Install]
WantedBy=default.target
"""


def unit_name(profile):
    return "hl-" + lease.identifier(profile) + ".service"


def unit_dir():
    return Path.home() / ".config" / "systemd" / "user"


def safe(value):
    # Unit files interpret %, quotes, backslashes and whitespace; accept plain absolute paths only.
    if not isinstance(value, str) or not SAFE_PATH.fullmatch(value) or ".." in Path(value).parts:
        raise ValueError("service paths must be plain absolute paths ([A-Za-z0-9_./-])")
    return value


def lab_search_dirs(root):
    """Where lab turn files would live: HOME, the root's parent, their direct subdirectories, and PATH."""
    directories = [Path.home(), root.parent]
    for base in (Path.home(), root.parent):
        try:
            directories += [child for count, child in zip(range(4096), base.iterdir())]
        except OSError:
            pass
    directories += [Path(entry) for entry in os.environ.get("PATH", "").split(os.pathsep) if entry]
    return list(dict.fromkeys(directories))


def lab_files(root):
    found = []
    for directory in lab_search_dirs(root):
        for name in LAB_FILES:
            try:
                if (directory / name).exists():
                    found.append(str(directory / name))
            except OSError:
                pass
    return found


def non_lab_root(payload):
    """The marked root, only when it is provably non-lab (fails closed)."""
    if payload.get("lab_dir") is not None:
        raise ValueError("non-lab service mode refused: a lab directory was given (lab machines use leases)")
    root = lease.marked_root(payload.get("root"))
    policy_file = lease.inside(root, "etc", "install-policy.json")
    if not policy_file.is_file():
        raise ValueError("non-lab service mode refused: etc/install-policy.json is missing; install the root "
                         "with lab_mode false first")
    policy = lease.read_json(policy_file)
    if not isinstance(policy, dict) or "lab_dir" not in policy or policy["lab_dir"] is not None:
        raise ValueError("non-lab service mode refused: this install root is in lab mode (its policy does not "
                         "record lab_dir null)")
    found = lab_files(root)
    if found:
        raise ValueError("non-lab service mode refused: lab turn files exist on this machine ("
                         + ", ".join(found[:4]) + "); lab machines run GPU work through leases only")
    return root


def systemctl(*args, check=True):
    if shutil.which("systemctl") is None:
        raise ValueError("systemctl is unavailable on this machine")
    result = subprocess.run(["systemctl", "--user", *args], capture_output=True, text=True, timeout=60,
                            stdin=subprocess.DEVNULL)
    if check and result.returncode:
        raise ValueError("systemctl --user " + args[0] + " failed: " + (result.stderr.strip() or "no user manager")
                         + " (a user manager must be running; enabling lingering is the user's own step)")
    return result


def unit_state(name):
    active = systemctl("is-active", name, check=False).stdout.strip()
    enabled = systemctl("is-enabled", name, check=False).stdout.strip()
    return active, enabled


def build_spec(root, payload):
    profile = lease.identifier(payload.get("profile"))
    processes = payload.get("processes")
    if not isinstance(processes, list):
        raise ValueError("processes must be a list")
    spec = lease.validate_spec({"root": str(root), "lab_dir": None, "label": lease.SERVICE_PREFIX + profile,
                                "kind": "none", "deadline_s": DEADLINE_S, "approval": None,
                                "profile": profile, "layout_required": None, "peer_ssh": None,
                                "peer_root": None, "processes": processes})
    releases = lease.inside(root, "releases").resolve()
    for proc in spec["processes"]:
        if proc["machine"] != "local":
            raise ValueError("non-lab service mode runs local processes only (no pair peers)")
        executable = lease.path(proc["argv"][0]).resolve()
        relative = executable.relative_to(releases) if executable.is_relative_to(releases) else None
        if relative is None or len(relative.parts) != 3 or relative.parts[1] != "bin":
            raise ValueError("service processes must run an immutable release executable")
    spec["service"] = True
    return profile, spec


def interpreter():
    # The interpreter as invoked (for example /usr/bin/python3), not its resolved versioned target, so a
    # distribution upgrade of python3 does not break the unit.
    value = sys.executable
    if not value or not value.startswith("/"):
        raise ValueError("the node interpreter path is unknown")
    return safe(posixpath.normpath(value))


def install(payload):
    root = non_lab_root(payload)
    safe(str(root))
    python = interpreter()
    profile, spec = build_spec(root, payload)
    enable = payload.get("enable", False)
    if type(enable) is not bool:
        raise ValueError("enable must be boolean")
    systemctl("show-environment")
    name = unit_name(profile)
    if systemctl("is-active", name, check=False).stdout.strip() in ACTIVE:
        raise ValueError("service is running; stop it before reinstalling")
    bin_dir = lease.inside(root, "bin")
    bin_dir.mkdir(exist_ok=True)
    here = Path(__file__).resolve().parent
    for filename in COPIED:
        lease.atomic(lease.inside(root, "bin", filename), (here / filename).read_bytes())
        os.chmod(lease.inside(root, "bin", filename), 0o700)
    spec_file = lease.inside(root, "etc", "service-" + profile + ".json")
    lease.write_json(spec_file, spec)
    unit = UNIT.format(profile=profile, root=root, python=python, spec=spec_file)
    directory = unit_dir()
    directory.mkdir(parents=True, exist_ok=True)
    lease.atomic(directory / name, unit.encode("ascii"))
    systemctl("daemon-reload")
    if enable:
        systemctl("enable", name)
    # Report what systemd says: a reinstall without --enable keeps an earlier enable.
    enabled = systemctl("is-enabled", name, check=False).stdout.strip()
    return {"unit": name, "unit_file": str(directory / name), "enabled": enabled == "enabled",
            "unit_file_state": enabled or None}


def service_records(root, profile):
    rows = []
    for filename in lease.inside(root, "run").glob("lease-*.json"):
        filename = lease.inside(root, "run", filename.name)
        state = lease.read_json(filename)
        if state.get("label") == lease.SERVICE_PREFIX + profile:
            rows.append((filename, state))
    rows.sort(key=lambda row: row[1].get("queued_at", 0))
    return rows


def settle_records(root, profile, reason):
    """Mark every non-terminal record of this unit failed: systemd runs one instance per unit, so a new start
    (or an inactive unit) means earlier records can never finish."""
    for filename, state in service_records(root, profile):
        if state.get("state") not in lease.TERMINAL:
            lease.settle_service(root, filename, state, reason)


def prune_records(root, profile, keep=KEEP_RECORDS):
    terminal = [state for _, state in service_records(root, profile) if state.get("state") in lease.TERMINAL]
    for state in terminal[:max(0, len(terminal) - keep)]:
        lid = lease.identifier(state["lease"])
        for pattern in ("lease-" + lid + ".*", "spec-" + lid + ".json", "owner-" + lid + ".json"):
            for filename in lease.inside(root, "run").glob(pattern):
                lease.inside(root, "run", filename.name).unlink(missing_ok=True)
        for filename in lease.inside(root, "log").glob("lease-" + lid + "-*.log"):
            lease.inside(root, "log", filename.name).unlink(missing_ok=True)


def status(payload):
    root = lease.marked_root(payload.get("root"))
    profile = lease.identifier(payload.get("profile"))
    shown = systemctl("show", unit_name(profile), "--property=LoadState,ActiveState,SubState,MainPID,"
                      "NRestarts,Result,UnitFileState", check=False)
    unit = dict(line.split("=", 1) for line in shown.stdout.splitlines() if "=" in line)
    if unit.get("ActiveState") in {"inactive", "failed"}:
        settle_records(root, profile, "stale: the unit is not running")
    lease.live_records(root)  # settles records whose process is gone
    records = [state for _, state in service_records(root, profile)]
    return {"unit": unit_name(profile), "systemd": unit, "production_mode": "non-lab",
            "lease": records[-1] if records else None}


def remove(payload):
    root = lease.marked_root(payload.get("root"))
    profile = lease.identifier(payload.get("profile"))
    name = unit_name(profile)
    # Without a user manager, disable cannot remove the default.target.wants link: refuse before changing files.
    systemctl("show-environment")
    if systemctl("is-active", name, check=False).stdout.strip() in ACTIVE:
        raise ValueError("service is running; stop it before removing")
    systemctl("disable", name)
    (unit_dir() / name).unlink(missing_ok=True)
    lease.inside(root, "etc", "service-" + profile + ".json").unlink(missing_ok=True)
    systemctl("daemon-reload")
    systemctl("reset-failed", name, check=False)
    settle_records(root, profile, "stale: the unit was removed")
    return {"unit": name, "removed": True}


def service_run(spec_file):
    """Unit entry: publish a lease record owned by this process, then supervise in the foreground."""
    spec_file = lease.path(spec_file)
    spec = lease.read_json(spec_file)
    if spec.get("service") is not True or spec.get("kind") != "none" or spec.get("lab_dir") is not None:
        raise ValueError("not a non-lab service spec")
    root = non_lab_root({"root": spec["root"]})
    profile = lease.identifier(spec["profile"])
    if spec_file.resolve() != lease.inside(root, "etc", "service-" + profile + ".json").resolve():
        raise ValueError("spec file must belong to this service")
    build_spec(root, spec)
    lid = uuid.uuid4().hex
    spec["lease"] = lid
    filename = lease.inside(root, "run", "spec-" + lid + ".json")
    with lease.root_lock(root):
        settle_records(root, profile, "stale: superseded by a new start of the unit")
        others = [state.get("label") for state in lease.live_records(root)]
        if others:
            raise ValueError("refused: a lease is live on this root (" + ", ".join(map(str, others)) + ")")
        lease.write_json(filename, spec)
        lease.write_json(lease.record_path(root, lid), {
            "lease": lid, "label": spec["label"], "kind": "service", "state": "queued", "queued_at": time.time(),
            "processes": [], "deadline_s": spec["deadline_s"], "approval": None, "reason": None,
            "profile": profile, "pid": os.getpid(), "boot_id": lease.boot_id()})
    prune_records(root, profile)
    lease.write_json(lease.inside(root, "run", "owner-" + lid + ".json"), {"pid": os.getpid()})
    lease.supervise(filename)
    state = lease.read_json(lease.record_path(root, lid))
    # Only a requested stop is a clean exit; an engine failure lets Restart=on-failure act, a readiness
    # timeout does not restart (it would only time out again).
    if state.get("state") == "stopped" and state.get("reason") == "requested":
        return 0
    if str(state.get("reason", "")).startswith("readiness-timeout:"):
        return EXIT_READY_TIMEOUT
    return 1


def run(verb, payload):
    result = {"schema": "hyperloom/node-v1", "verb": verb}
    try:
        if verb not in VERBS or not isinstance(payload, dict):
            raise ValueError("unsupported service verb or payload")
        if verb == "service-install":
            result.update(install(payload))
        elif verb == "service-status":
            result.update(status(payload))
        elif verb == "service-remove":
            result.update(remove(payload))
        else:
            name = unit_name(payload.get("profile"))
            if verb == "service-start":
                root = non_lab_root(payload)
                own = lease.SERVICE_PREFIX + lease.identifier(payload.get("profile"))
                others = [str(state.get("label")) for state in lease.live_records(root) if state.get("label") != own]
                if others:
                    raise ValueError("refused: a lease is live on this root (" + ", ".join(others) + ")")
            else:
                lease.marked_root(payload.get("root"))  # stopping is always allowed
            # --no-block: the stop drains through supervise for up to TimeoutStopSec; the control machine
            # polls service-status instead of holding this call open.
            systemctl("start" if verb == "service-start" else "stop", "--no-block", name)
            result.update(unit=name, requested=verb[8:])
    except (ValueError, OSError, KeyError, TypeError, UnicodeError, subprocess.SubprocessError) as exc:
        result["error"] = str(exc)
    return result


def main(argv):
    if len(argv) == 3 and argv[1] == "service-run":
        try:
            return service_run(argv[2])
        except (ValueError, OSError, KeyError, TypeError, UnicodeError) as exc:
            print("hyperloom service refused: " + str(exc), file=sys.stderr, flush=True)
            return EXIT_REFUSED
    print("internal service entry point only", file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
